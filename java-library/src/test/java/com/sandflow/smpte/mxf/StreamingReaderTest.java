  @Test
  void testVBE() throws Exception {
    List<Long> actualSizes = Arrays.asList(1964L, 1296L, 1965L, 2023L, 1698L, 1966L, 2063L, 1618L, 2100L, 2068L,
        2520L, 1846L, 2475L, 2540L, 2214L, 2486L, 2615L, 2150L, 2628L, 2614L, 3058L, 2472L, 2992L, 3093L);

    InputStream is = ClassLoader.getSystemResourceAsStream("mxf-files/video.mxf");
    assertNotNull(is);

    StreamingFileInfo info = new StreamingFileInfo(is, null);
    GCEssenceTracks tracks = new GCEssenceTracks(info.getPreface());
    assertEquals(1, tracks.getTrackCount());
    RGBADescriptor d = (RGBADescriptor) tracks.getTrackInfo(0).getDescriptor();
    assertEquals(640L, d.StoredWidth);

    StreamingReader sr = new StreamingReader(is, null);
    ArrayList<Long> measuredSizes = new ArrayList<>();
    while (sr.nextElement()) {
      measuredSizes.add(sr.getElementLength());
    }

    assertIterableEquals(actualSizes, measuredSizes);

    sr.close();
  }

  @Test
  void testCBE() throws Exception {
    InputStream is = ClassLoader.getSystemResourceAsStream("mxf-files/audio.mxf");

    StreamingFileInfo info = new StreamingFileInfo(is, null);
    GCEssenceTracks tracks = new GCEssenceTracks(info.getPreface());
    assertEquals(1, tracks.getTrackCount());

    StreamingReader sr = new StreamingReader(is, null);

    int i = 0;
    while (sr.nextElement()) {
      WAVEPCMDescriptor d = (WAVEPCMDescriptor) tracks.getTrackInfo(sr.getElementKey()).getDescriptor();
      assertEquals(d.AverageBytesPerSecond, 288000);
      i++;
      assertEquals(288000, sr.getElementLength());
    }

    assertEquals(1, i);

    sr.close();

  }

  /*
   * SMPTE ST 2067-206 Timed Events Track File generated by bmx
   * (https://github.com/ebu/bmx/pull/46)
   */
  @Test
  void testTimedEvents() throws Exception {
    InputStream is = ClassLoader.getSystemResourceAsStream("mxf-files/timed_events.mxf");
    assertNotNull(is);

    StreamingFileInfo info = new StreamingFileInfo(is, null);
    GCEssenceTracks tracks = new GCEssenceTracks(info.getPreface());
    assertEquals(1, tracks.getTrackCount());

    TimedEventsTextDescriptor d = (TimedEventsTextDescriptor) tracks.getTrackInfo(0).getDescriptor();
    assertEquals("text/xml", d.TextMIMEType);
    assertEquals("UTF-8", d.TextCharacterEncoding);
    assertEquals("http://www.example.com/props http://www.smpte-ra.org/ns/2067-206/2023/simple-scheme",
        d.EventSchemeURIs);
    assertEquals(Labels.MXFGCTimedEventsTextStream, d.ContainerFormat);
    assertEquals(1, d.SubDescriptors.size());

    TimedEventsAncillaryResourceSubDescriptor sd = (TimedEventsAncillaryResourceSubDescriptor) d.SubDescriptors
        .iterator().next();
    assertEquals("first.jpg", sd.TimedEventsAncillaryResourceID);
    assertEquals("image/png", sd.TimedEventsAncillaryResourceMIMEType);
    assertEquals(12L, sd.TimedEventsAncillaryResourceStreamID);

    StreamingReader sr = new StreamingReader(is, null);

    /* Timed Events Resource */

    assertTrue(sr.nextElement());
    assertEquals(tracks.getTrackInfo(0).getContainer().EssenceStreamID, sr.getSID());
    assertEquals(840L, sr.getElementLength());
    assertNotNull(tracks.getTrackInfo(sr.getElementKey()));
    assertArrayEquals("<?xml".getBytes(), sr.readNBytes(5));

    /* Timed Events Ancillary Resource, in a generic stream */

    assertTrue(sr.nextElement());
    assertEquals(sd.TimedEventsAncillaryResourceStreamID, sr.getSID());
    assertArrayEquals(UL.fromURN("urn:smpte:ul:060e2b34.0101010c.0d010509.01000000").getBytes(),
        sr.getElementKey().getBytes());
    assertEquals(81L, sr.getElementLength());
    /* the ancillary resource is a placeholder text file */
    assertArrayEquals("This is pretending".getBytes(), sr.readNBytes(18));

    assertFalse(sr.nextElement());

    sr.close();
  }

  /*
   * SMPTE ST 2067-204 ADM audio track file, from the Photon test suite
   * (https://github.com/wruppelx/photon)
   */
  @Test
  void testST2067204() throws Exception {
    InputStream is = ClassLoader.getSystemResourceAsStream("mxf-files/st2067-204.mxf");
    assertNotNull(is);

    StreamingFileInfo info = new StreamingFileInfo(is, null);
    GCEssenceTracks tracks = new GCEssenceTracks(info.getPreface());
    assertEquals(1, tracks.getTrackCount());

    /* ST 2067-204 Clauses 5.3 and 5.4 */
    FileDescriptor d = tracks.getTrackInfo(0).getDescriptor();
    assertEquals(Labels.AudioLabelingFrameworkADMContent, ((WAVEPCMDescriptor) d).ChannelAssignment);
    assertNotNull(d.SubDescriptors);
    assertTrue(d.SubDescriptors.stream().anyMatch(sd -> sd instanceof RIFFChunkDefinitionSubDescriptor));
    assertTrue(d.SubDescriptors.stream().anyMatch(sd -> sd instanceof ADMAudioMetadataSubDescriptor));
    assertTrue(d.SubDescriptors.stream().anyMatch(sd -> sd instanceof ADMSoundfieldGroupLabelSubDescriptor));
    assertFalse(d.SubDescriptors.stream().anyMatch(sd -> sd instanceof AudioChannelLabelSubDescriptor
        || sd instanceof GroupOfSoundfieldGroupsLabelSubDescriptor
        || (sd instanceof SoundfieldGroupLabelSubDescriptor && !(sd instanceof ADMSoundfieldGroupLabelSubDescriptor))));
    d.SubDescriptors.stream().filter(sd -> sd instanceof ADMSoundfieldGroupLabelSubDescriptor).forEach(sd -> {
      ADMSoundfieldGroupLabelSubDescriptor sg = (ADMSoundfieldGroupLabelSubDescriptor) sd;
      assertNotNull(sg.MCALabelDictionaryID);
      assertNotNull(sg.MCATagSymbol);
      assertEquals(null, sg.MCAChannelID);
    });

    StreamingReader sr = new StreamingReader(is, null);

    int i = 0;
    while (sr.nextElement()) {
      assertTrue(sr.getElementLength() > 0);
      i++;
    }

    assertTrue(i > 0);

    sr.close();
  }

  /*
   * SMPTE ST 2067-204 example ADM Audio Track File (Operational Mode A)
   * https://pub.smpte.org/doc/st2067-204/20260527-pub/
   */
  @Test
  void testST2067204ModeA() throws Exception {
    InputStream is = ClassLoader.getSystemResourceAsStream("mxf-files/st2067-204b-2026-05.mxf");
    assertNotNull(is);

    StreamingFileInfo info = new StreamingFileInfo(is, null);
    GCEssenceTracks tracks = new GCEssenceTracks(info.getPreface());
    assertEquals(1, tracks.getTrackCount());

    FileDescriptor d = tracks.getTrackInfo(0).getDescriptor();
    assertEquals(Labels.AudioLabelingFrameworkADMContent, ((WAVEPCMDescriptor) d).ChannelAssignment);
    assertTrue(d.SubDescriptors.stream().anyMatch(sd -> sd instanceof RIFFChunkDefinitionSubDescriptor));
    assertTrue(d.SubDescriptors.stream().anyMatch(sd -> sd instanceof ADMAudioMetadataSubDescriptor));

    /* stereo and 5.1 versions */
    List<ADMSoundfieldGroupLabelSubDescriptor> groups = new ArrayList<>();
    d.SubDescriptors.forEach(sd -> {
      if (sd instanceof ADMSoundfieldGroupLabelSubDescriptor) {
        groups.add((ADMSoundfieldGroupLabelSubDescriptor) sd);
      }
    });
    assertEquals(2, groups.size());
    for (ADMSoundfieldGroupLabelSubDescriptor sg : groups) {
      assertNotNull(sg.ADMAudioProgrammeID_ST2131);
      assertEquals(null, sg.ADMAudioContentID_ST2131);
      assertEquals(null, sg.ADMAudioObjectID_ST2131);
      assertEquals(null, sg.MCAChannelID);
    }

    StreamingReader sr = new StreamingReader(is, null);
    int i = 0;
    while (sr.nextElement()) {
      assertTrue(sr.getElementLength() > 0);
      i++;
    }
    assertTrue(i > 0);
    sr.close();
  }

